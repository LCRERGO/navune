func TestTokensNormalizeLiteralsKeepIdents(t *testing.T) {
	src := `package x
func f() {
	a := "hello"
	b := 42
	c := a
	_ = b
	_ = c
}
`
	res, err := New().Parse("x.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	var strs, nums int
	for _, tok := range res.Tokens {
		switch tok.Kind {
		case lang.TokString:
			strs++
			if tok.Text != "STR" {
				t.Errorf("string literal should normalize to STR, got %q", tok.Text)
			}
		case lang.TokNumber:
			nums++
			if tok.Text != "NUM" {
				t.Errorf("number should normalize to NUM, got %q", tok.Text)
			}
		}
	}
	if strs != 1 || nums != 1 {
		t.Errorf("want 1 string + 1 number token, got %d + %d", strs, nums)
	}
	hasIdent := false
	for _, tok := range res.Tokens {
		if tok.Kind == lang.TokIdent && tok.Text == "hello" {
			hasIdent = true
		}
	}
	// identifier 'hello' is inside a string literal so must NOT appear
	if hasIdent {
		t.Error("string contents must not leak into the token stream")
	}
}
